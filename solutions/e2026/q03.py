def result1(line):
    line_clean = line.strip("ISO-").split()
    sum = 0
    it = len(line_clean[0]) - 1
    for i in range(len(line_clean[0])):
        sum += int(line_clean[1][i]) * (int(line_clean[0][i]) ** it)
        it -= 1
    return sum


