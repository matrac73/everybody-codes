def order1(line):
    line = line[0].split()
    sol = {}
    for num in [1, 2, 3, 4, 5]:
        line_num = [comp for comp in line if str(num) in comp]
        rank_num = 5
        for comp in line_num:
            if (
                comp[0] == str(num)
                and comp[1] == ">"
                or comp[2] == str(num)
                and comp[1] == "<"
            ):
                rank_num -= 1
        sol[str(num)] = str(rank_num)
    out = ""
    keys = list(sol.keys())
    cat = list(sol.values())
    for i in [1, 2, 3, 4, 5]:
        out += keys[cat.index(str(i))]
    return int(out)


def sum_order1(lines):
    return sum([order1(line) for line in lines])


