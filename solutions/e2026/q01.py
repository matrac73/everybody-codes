def missing(c: int) -> int:
    k = m.isqrt(c) + 1
    if k % 2 == 0:
        k += 1
    k = max(k, 3)
    return k * k - 1 - c

def part3(data: list[int]) -> int:
    return sum(missing(c) for c in data)

